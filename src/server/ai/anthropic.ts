import type {
  AiContext,
  AiProvider,
  AiResult,
} from "@/server/ai/provider";

/**
 * Anthropic-backed provider.
 *
 * Selected only when `ANTHROPIC_API_KEY` is present. The key is read inside
 * the request, lives only on the server, and is never passed to a client
 * component or embedded in a payload.
 *
 * **This path is not covered by the test suite**, because testing it requires
 * a paid API key that this project does not have and will not purchase. It is
 * written to the documented Messages API shape, and the error handling below
 * is what runs if the shape is wrong. The mock provider is the tested path and
 * the default. That caveat is in the README too — a portfolio project claiming
 * verified behaviour it has not verified is worse than one that says so.
 */

const API_URL = "https://api.anthropic.com/v1/messages";
const API_VERSION = "2023-06-01";
const DEFAULT_MODEL = "claude-sonnet-4-5";
const TIMEOUT_MS = 20_000;

function systemPrompt(): string {
  return [
    "You are assisting a human customer-support agent inside a ticketing tool.",
    "Be concise and factual. Never invent product behaviour, account details, refunds, dates or commitments.",
    "If the provided context does not answer the question, say so plainly rather than guessing.",
    "The agent reviews and edits everything before it reaches the customer.",
  ].join(" ");
}

function renderContext(context: AiContext): string {
  const thread = context.messages
    .map(
      (message) =>
        `[${message.createdAt}] ${message.authorName} (${message.authorKind}${message.internal ? ", internal note" : ""}): ${message.body}`,
    )
    .join("\n\n");

  const articles = context.articles
    .map((article) => `### ${article.title} (${article.slug})\n${article.body}`)
    .join("\n\n");

  return [
    `Ticket ${context.ticket.reference}: ${context.ticket.subject}`,
    `Status ${context.ticket.status}, priority ${context.ticket.priority}, channel ${context.ticket.channel}.`,
    `Customer: ${context.ticket.customer.name} at ${context.ticket.customer.company} (${context.ticket.customer.plan} plan).`,
    `\n## Conversation\n${thread}`,
    articles ? `\n## Knowledge base\n${articles}` : "",
  ].join("\n");
}

export class AnthropicAiProvider implements AiProvider {
  readonly name = "anthropic";
  readonly simulated = false;

  readonly #apiKey: string;
  readonly #model: string;

  constructor(apiKey: string, model = process.env.ANTHROPIC_MODEL ?? DEFAULT_MODEL) {
    this.#apiKey = apiKey;
    this.#model = model;
  }

  async #call(prompt: string, context: AiContext): Promise<AiResult> {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        signal: controller.signal,
        headers: {
          "content-type": "application/json",
          "x-api-key": this.#apiKey,
          "anthropic-version": API_VERSION,
        },
        body: JSON.stringify({
          model: this.#model,
          max_tokens: 1024,
          system: systemPrompt(),
          messages: [
            { role: "user", content: `${prompt}\n\n${renderContext(context)}` },
          ],
        }),
      });

      if (!response.ok) {
        // Never surface the provider's raw body: it can echo request content.
        return {
          ok: false,
          provider: this.name,
          simulated: false,
          error:
            response.status === 429
              ? "The AI provider is rate-limiting requests. Try again shortly."
              : `The AI provider returned ${response.status}. The mock provider remains available.`,
        };
      }

      const payload = (await response.json()) as {
        content?: { type: string; text?: string }[];
      };
      const text =
        payload.content
          ?.filter((block) => block.type === "text")
          .map((block) => block.text ?? "")
          .join("\n")
          .trim() ?? "";

      if (!text) {
        return {
          ok: false,
          provider: this.name,
          simulated: false,
          error: "The AI provider returned an empty response.",
        };
      }

      return {
        ok: true,
        provider: this.name,
        simulated: false,
        output: {
          text,
          notes: [`Generated by ${this.#model}. Review before sending.`],
          citations: context.articles.map((article) => article.slug),
        },
      };
    } catch (error) {
      const aborted = error instanceof Error && error.name === "AbortError";
      return {
        ok: false,
        provider: this.name,
        simulated: false,
        error: aborted
          ? "The AI provider timed out after 20 seconds."
          : "Could not reach the AI provider.",
      };
    } finally {
      clearTimeout(timer);
    }
  }

  summarise(context: AiContext): Promise<AiResult> {
    return this.#call(
      "Summarise this support ticket for an agent picking it up cold: what the customer reported, what has been tried, and what the next action should be. Use short paragraphs.",
      context,
    );
  }

  draftReply(context: AiContext, instruction: string): Promise<AiResult> {
    return this.#call(
      `Draft a reply to the customer for the agent to review and edit.${
        instruction.trim() ? ` Additional instruction: ${instruction.trim()}` : ""
      }`,
      context,
    );
  }
}
